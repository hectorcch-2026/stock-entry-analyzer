const ZH_KEYS = Object.keys(ZH);
const CN_RE = /[\u4e00-\u9fff]/;

/** 是否含中文 */
function hasChinese(s) {
  return CN_RE.test(s);
}

/**
 * 由中文關鍵字查詢代碼
 * @returns {Array<{symbol:string,name:string,matched:string}>} 依匹配品質排序
 */
function searchChinese(q) {
  const key = String(q || '').trim();
  if (!key) return [];

  const exact = [];
  const prefix = [];
  const contains = [];

  for (const name of ZH_KEYS) {
    const symbol = ZH[name];
    if (name === key) exact.push({ symbol, name, matched: name });
    else if (name.startsWith(key) || key.startsWith(name)) prefix.push({ symbol, name, matched: name });
    else if (name.includes(key) || key.includes(name)) contains.push({ symbol, name, matched: name });
  }

  // 同一代碼可能由多個別名命中，去重並保留最長匹配（最具體）
  const seen = new Map();
  for (const item of exact.concat(prefix, contains)) {
    const prev = seen.get(item.symbol);
    if (!prev || item.matched.length > prev.matched.length) seen.set(item.symbol, item);
  }
  return [...seen.values()];
}

/** 由英文關鍵字查代碼（完全相符才採用，避免誤判） */
function lookupEnglish(q) {
  const k = String(q || '').trim().toLowerCase();
  if (!k) return null;
  if (EN[k]) return EN[k];
  const hit = Object.keys(EN).find((x) => x.toLowerCase() === k);
  return hit ? EN[hit] : null;
}

/** 提供給前端的熱門中文名稱建議（用於自動完成） */
function suggestions(q) {
  const key = String(q || '').trim();
  if (!key) return [];
  return searchChinese(key).slice(0, 8).map((x) => ({
    symbol: x.symbol,
    name: x.name,
    shortName: x.name,
    exchange: /\.HK$/.test(x.symbol) ? 'Hong Kong' : 'United States',
    market: /\.HK$/.test(x.symbol) ? 'HK' : 'US',
    type: 'EQUITY',
    fromAlias: true,
  }));
}

